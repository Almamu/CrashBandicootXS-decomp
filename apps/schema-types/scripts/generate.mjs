// The data files' TypeScript types, from packages/crashdata/schemas/ (#1167,
// docs/editors.md "The TypeScript workspace").
//
//   pnpm --filter @crash/schema-types gen          write src/generated/
//   pnpm --filter @crash/schema-types gen:check    fail if src/generated/ is out of date (CI)
//
// One module per schema (room.schema.json -> room.ts, its type Room) and
// index.ts: every type, SchemaFiles (schema file name -> its type) and
// SCHEMA_NAMES. The output is committed, like the schemas: a change to the
// model comes with `make schemas` and then this.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
export const SCHEMAS_DIR = resolve(here, "../../../packages/crashdata/schemas");
export const OUT_DIR = resolve(here, "../src/generated");

const BANNER = (name) =>
  `// Generated by apps/schema-types/scripts/generate.mjs from\n` +
  `// packages/crashdata/schemas/${name} (docs/editors.md): don't edit.\n` +
  `// \`make schemas\`, then \`pnpm gen\`, after a change to crashdata's model.\n`;

/** room.schema.json -> Room, gax_sfx_manifest.schema.json -> GaxSfxManifest */
export function typeName(file) {
  return file
    .replace(/\.schema\.json$/, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
}

export function moduleName(file) {
  return file.replace(/\.schema\.json$/, "");
}

/** {file name in src/generated/: its text} */
export async function render(schemasDir = SCHEMAS_DIR) {
  const index = JSON.parse(readFileSync(join(schemasDir, "index.json"), "utf8"));
  const names = readdirSync(schemasDir)
    .filter((f) => f.endsWith(".schema.json"))
    .sort();
  const out = {};
  for (const file of names) {
    const schema = JSON.parse(readFileSync(join(schemasDir, file), "utf8"));
    // the type's name is the file's, not the schema's title (a sentence)
    const { $id: _id, title: _title, ...rest } = schema;
    const ts = await compile({ ...rest, title: typeName(file) }, typeName(file), {
      bannerComment: BANNER(file),
      additionalProperties: false,
      unreachableDefinitions: false,
      strictIndexSignatures: true,
      declareExternallyReferenced: true,
      cwd: schemasDir,
      format: true,
      style: { singleQuote: false, printWidth: 110, trailingComma: "all" },
    });
    out[`${moduleName(file)}.ts`] = ts;
  }
  const lines = [BANNER("*.schema.json and index.json").trimEnd(), ""];
  for (const file of names) {
    lines.push(`import type { ${typeName(file)} } from "./${moduleName(file)}.ts";`);
  }
  lines.push("");
  for (const file of names) {
    lines.push(`export type { ${typeName(file)} } from "./${moduleName(file)}.ts";`);
    lines.push(`export type * as ${typeName(file)}Defs from "./${moduleName(file)}.ts";`);
  }
  lines.push("", "/** Each schema's file name, and the type of the files it describes. */");
  lines.push("export interface SchemaFiles {");
  for (const file of names) lines.push(`  "${file}": ${typeName(file)};`);
  lines.push("}", "");
  lines.push("export type SchemaName = keyof SchemaFiles;", "");
  lines.push("/** The schemas, as packages/crashdata/schemas/ has them. */");
  lines.push("export const SCHEMA_NAMES = [");
  for (const file of names) lines.push(`  "${file}",`);
  lines.push("] as const satisfies readonly SchemaName[];", "");
  lines.push("/** index.json's globs: the files each schema describes, from the tree's root. */");
  lines.push("export const FILE_MATCH: Readonly<Record<SchemaName, readonly string[]>> = {");
  const byName = Object.fromEntries(index.schemas.map((s) => [s.schema, s.fileMatch]));
  for (const file of names) {
    lines.push(`  "${file}": [${(byName[file] ?? []).map((g) => JSON.stringify(g)).join(", ")}],`);
  }
  lines.push("};", "");
  out["index.ts"] = lines.join("\n");
  return out;
}

async function main() {
  const check = process.argv.includes("--check");
  const want = await render();
  const have = existsSync(OUT_DIR) ? readdirSync(OUT_DIR).filter((f) => f.endsWith(".ts")) : [];
  const stale = [];
  for (const [name, text] of Object.entries(want)) {
    const p = join(OUT_DIR, name);
    if (!existsSync(p) || readFileSync(p, "utf8") !== text) stale.push(name);
  }
  const extra = have.filter((f) => !(f in want));
  if (check) {
    for (const f of stale) console.error(`apps/schema-types/src/generated/${f}: out of date: run \`pnpm gen\``);
    for (const f of extra) console.error(`apps/schema-types/src/generated/${f}: no schema gives it: run \`pnpm gen\``);
    process.exit(stale.length || extra.length ? 1 : 0);
  }
  mkdirSync(OUT_DIR, { recursive: true });
  for (const name of stale) writeFileSync(join(OUT_DIR, name), want[name]);
  for (const f of extra) rmSync(join(OUT_DIR, f));
  console.log(`schema-types: ${Object.keys(want).length} files, ${stale.length + extra.length} changed`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
