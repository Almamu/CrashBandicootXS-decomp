#!/usr/bin/env python3
"""Regenerates the N-Tranced code's disassembly (games/n2/asm/) and the
linker script (games/n2/ldscript.txt), with gbadisasm.

    python3 games/n2/disasm.py path/to/gbadisasm [baserom_n2.gba]

gbadisasm (jiangzhengwenjz/gbadisasm, new_features) disassembles the ROM
from games/n2/gbadisasm.cfg: crt0, the N-Tranced address of every XS
function found in it (XS's name where only one XS function is that code),
and the code pointers' targets; it follows the calls from there. Then:

- `adds rN, rN, #k` is written as its bytes: the ROM has the 3-register
  encoding (0x1C00) and GAS would pick `adds rN, #k` (0x3000). The ROM's
  are all GAX's DMA-wait `adds r3, r3, #0`, the same idiom XS's
  disassembly spelled as bytes.
- The code is cut around the shared sources of games/n2/objects.txt,
  which are linked in its place: one asm file per stretch between them,
  `asm/code_<address>.s`, each ending with `.align 2, 0` (zero padding,
  not a Thumb nop). A function the disassembly calls inside a cut-out
  stretch has to be named as the source names it (gbadisasm.cfg).
- Only the code is kept (up to CODE_END). The rest of the ROM, the data,
  is games/n2/data/data_<address>.s (also written here): the original's
  bytes, incbin'd, with a global label at every address in it the code
  points at, named after XS's (games/n2/data_names.txt) or
  gUnknown_<address>, cut around the data objects of objects.txt (its
  entries after the code: data built from sources, such as the level
  assets), which the linker script places there.
- A literal-pool word whose value is such a label, or a RAM variable
  games/n2/symbols.txt names, is written as the name (`.4byte
  gLevelTable`), and so is the `ldr`'s `@ =` comment; the linker gives it
  the same value, and a label moves with its data.
- So is a pool word that points into the code: at a function, its name
  (a Thumb function's symbol already has bit 0 set; for the address
  without it, a plain `_<address>` label is added at the function); at
  any other label, that label (`+ 1` for a Thumb address), made global,
  since the code is split across files. gbadisasm.cfg's `data_label`s give the ones that
  had no label one (the ROM header's game code, GAX's ARM routines,
  which are copied to RAM). A pool word into the code with no label to
  use stops the script.
"""
import re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CODE_START, CODE_END = 0x08000000, 0x0805BEA8
BUILD = 'build/ntranced'

HEADER = """\
@ Crash Bandicoot 2: N-Tranced (Europe): the code, 0x%08X-0x%08X.
@ Generated by games/n2/disasm.py from games/n2/gbadisasm.cfg; regenerate
@ instead of editing while it is still the bootstrap (docs/n_tranced.md).

\t.include "asm/macros.inc"

\t.syntax unified

\t.text

"""

LDSCRIPT = """\
/* Generated by games/n2/disasm.py from games/n2/objects.txt: the N-Tranced
 * ROM in order, its disassembly and the shared sources linked in its
 * place, then the incbin'd rest (docs/n_tranced.md). */
OUTPUT_ARCH(arm)
SECTIONS
{
\t. = 0x08000000;
\tROM :
\tALIGN(4)
\t{
%s
\t} = 0

\tINCLUDE "games/n2/symbols.txt"

\t/DISCARD/ :
\t{
\t\t*(.comment);
\t\t*(.ARM.attributes);
\t}
}
"""

DATA_HEADER = """\
@ Crash Bandicoot 2: N-Tranced (Europe): the data, 0x%08X-0x%08X, still the
@ original's bytes (baserom_n2.gba), with a label at every address the code
@ points at. Generated by games/n2/disasm.py: the names are
@ games/n2/data_names.txt's, the rest gUnknown_<address>.

\t.section .rodata

"""

SYMBOL = re.compile(r'^(\w+) = (0x[0-9A-Fa-f]+);')
DATA_NAME = re.compile(r'^(0x[0-9A-Fa-f]+)\s+(\w+)')
WORD = re.compile(r'(\.4byte |@ =)0x([0-9A-F]{8})\b')
ADDS = re.compile(r'^\tadds (r([0-7])), \1, #(0x[0-9a-fA-F]+|\d+)$')
LABEL = re.compile(r'^(\w+): @ 0x([0-9A-Fa-f]{8})$')
LOCAL = re.compile(r'^(_([0-9A-F]{8})):')


def object_path(src):
    """A source's object, under the build directory: games/n2/src/<path>
    builds src/<path>'s object (game.mk)."""
    if src.startswith('games/n2/src/'):
        src = src[len('games/n2/'):]
    return src.rsplit('.', 1)[0]


def objects():
    out = []
    for line in (HERE / 'objects.txt').read_text().splitlines():
        line = line.split('#')[0].split()
        if line:
            out.append((int(line[0], 16), int(line[1], 16), line[2]))
    return out


def main():
    gbadisasm = sys.argv[1]
    rom = sys.argv[2] if len(sys.argv) > 2 else str(ROOT / 'baserom_n2.gba')
    out = subprocess.run([gbadisasm, rom, '-c', str(HERE / 'gbadisasm.cfg')],
                         capture_output=True, text=True, check=True).stdout.split('\n')
    rom_end = 0x08000000 + Path(rom).stat().st_size
    names = {}
    for line in (HERE / 'symbols.txt').read_text().splitlines():
        m = SYMBOL.match(line)
        if m:
            names[int(m.group(2), 16)] = m.group(1)
    # the data the code points at: a label each
    data = {}
    for line in (HERE / 'data_names.txt').read_text().splitlines():
        m = DATA_NAME.match(line)
        if m:
            data[int(m.group(1), 16)] = m.group(2)
    for line in out:
        for m in WORD.finditer(line):
            v = int(m.group(2), 16)
            if CODE_END <= v < rom_end and v not in data:
                data[v] = 'gUnknown_%08X' % v
    names.update(data)

    # the code's own labels, for the pool words that point into the code
    funcs, local = {}, {}
    for i, line in enumerate(out):
        m = LABEL.match(line)
        if m and i and 'thumb_func_start' in out[i - 1]:
            funcs[int(m.group(2), 16)] = m.group(1)
        m = LOCAL.match(line)
        if m:
            local[int(m.group(2), 16)] = m.group(1)
    exported, aliases = set(), set()

    def code_ref(v):
        t = v & ~1
        if t in funcs and v & 1:
            return funcs[t]
        if t in funcs:
            aliases.add(t)
            return '_%08X' % t
        if t in local:
            exported.add(local[t])
            return local[t] + (' + 1' if v & 1 else '')
        sys.exit('a pool word points into the code at 0x%08X, where there is no label '
                 '(add a data_label or thumb_label to gbadisasm.cfg)' % v)

    def word(m):
        v = int(m.group(2), 16)
        if v in names:
            return m.group(1) + names[v]
        if CODE_START <= v < CODE_END:
            return m.group(1) + code_ref(v)
        return m.group(0)

    lines = []
    for line in out:
        line = WORD.sub(word, line)
        m = ADDS.match(line)
        if m:
            n, k = int(m.group(2)), int(m.group(3), 0)
            line = '\t.2byte 0x%04X @ adds %s, %s, #%d (GAS would pick the 0x3000 encoding)' % (
                0x1C00 | k << 6 | n << 3 | n, m.group(1), m.group(1), k)
        lines.append(line)

    # gbadisasm writes the words at its own labels as the labels: those are
    # used across files too
    for l in lines:
        exported.update(re.findall(r'\.4byte (_[0-9A-F]{8})\b', l))
    lines = [('\t.global %s\n' % LOCAL.match(l).group(1) + l)
             if LOCAL.match(l) and LOCAL.match(l).group(1) in exported else l for l in lines]
    # a plain label after the function's: its address without the Thumb bit
    lines = [(l + '\n\t.global _%08X\n_%08X:' % ((int(LABEL.match(l).group(2), 16),) * 2))
             if LABEL.match(l) and int(LABEL.match(l).group(2), 16) in aliases else l for l in lines]

    # where each function starts: the line of its `*_func_start`
    starts = {}
    for i, line in enumerate(lines):
        m = LABEL.match(line)
        if m and i and '_func_start' in lines[i - 1]:
            starts[int(m.group(2), 16)] = i - 1
    starts[CODE_END] = len(lines)

    objs = [o for o in objects() if o[0] < CODE_END]
    data_objs = [o for o in objects() if o[0] >= CODE_END]
    cuts = []  # (first line, end line) of each object's stretch
    for addr, size, src in objs:
        for a in (addr, addr + size):
            if a not in starts:
                sys.exit('%s: no function starts at 0x%08X in the disassembly' % (src, a))
        cuts.append((starts[addr], starts[addr + size]))

    asm = HERE / 'asm'
    for f in asm.glob('*.s'):
        f.unlink()
    script = []
    pos, at = 0, CODE_START
    pieces = [(cs, ce, o) for (cs, ce), o in zip(cuts, objs)] + [(len(lines), len(lines), None)]
    for cs, ce, o in pieces:
        if cs > pos:
            name = 'code_%08X' % at
            body = '\n'.join(lines[pos:cs]).strip('\n')
            (asm / (name + '.s')).write_text(HEADER % (at, o[0] if o else CODE_END) + body + '\n\t.align 2, 0\n')
            script.append('\t\t%s/games/n2/asm/%s.o(.text);' % (BUILD, name))
        if o:
            script.append('\t\t%s/%s.o(.text);' % (BUILD, object_path(o[2])))
            at = o[0] + o[1]
        pos = ce


    # the data: the original's bytes, cut around the data objects (built
    # from sources, objects.txt's entries after the code)
    for f in (HERE / 'data').glob('*.s'):
        f.unlink()
    for addr, size, src in data_objs:
        inside = [n for a, n in data.items() if addr < a < addr + size]
        if inside:
            sys.exit('%s: the code points inside it (%s): the object has to define those symbols'
                     % (src, ', '.join(inside[:4])))
    data_script, pos = [], CODE_END
    for start, end, src in [(a, a + n, s) for a, n, s in data_objs] + [(rom_end, rom_end, None)]:
        if start > pos:
            body, at = [], pos
            for addr in sorted(a for a in data if pos <= a < start) + [start]:
                if addr > at:
                    body.append('\t.incbin "baserom_n2.gba", 0x%X, 0x%X' % (at - 0x08000000, addr - at))
                if addr < start:
                    body.append('\n\t.global %s\n%s:' % (data[addr], data[addr]))
                at = addr
            name = 'data_%08X' % pos
            # after a data object, whose section ends with its last byte: a
            # word-aligned piece is aligned, the linker's zero fill being the
            # original's padding
            align = '\t.balign 4\n\n' if pos % 4 == 0 and pos != CODE_END else ''
            (HERE / 'data' / (name + '.s')).write_text(DATA_HEADER % (pos, start) + align + '\n'.join(body) + '\n')
            data_script.append('\t\t%s/games/n2/data/%s.o(.rodata);' % (BUILD, name))
        if src:
            data_script.append('\t\t%s/%s.o(.rodata);' % (BUILD, object_path(src)))
        pos = end
    (HERE / 'ldscript.txt').write_text(LDSCRIPT % ('\n'.join(script + data_script)))

    # labels cut out with an object but still used by the disassembly
    kept = '\n'.join(l for k, l in enumerate(lines) if not any(cs <= k < ce for cs, ce in cuts))
    for cs, ce in cuts:
        for k in range(cs, ce):
            m = LABEL.match(lines[k])
            if m and re.search(r'\b%s\b' % m.group(1), kept):
                print('note: %s (0x%s) is cut out but still used: the object must define it'
                      % (m.group(1), m.group(2)))


if __name__ == '__main__':
    main()
