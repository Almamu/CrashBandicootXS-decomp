#!/usr/bin/env python3
"""Regenerates the N-Tranced code's disassembly (games/n2/asm/) and the
linker script (games/n2/ldscript.txt), with gbadisasm.

    python3 games/n2/disasm.py path/to/gbadisasm [baserom_n2.gba]

gbadisasm (jiangzhengwenjz/gbadisasm, new_features) disassembles the ROM
from games/n2/gbadisasm.cfg: crt0, the N-Tranced address of every XS
function found in it (XS's name where only one XS function is that code),
and the code pointers' targets; it follows the calls from there. Then:

- `adds rN, rN, #k` is written as its bytes: the ROM has the 3-register
  encoding (0x1C00) and GAS would pick `adds rN, #k` (0x3000). The ROM's
  are all GAX's DMA-wait `adds r3, r3, #0`, the same idiom XS's
  disassembly spelled as bytes.
- The code is cut around the shared sources of games/n2/objects.txt,
  which are linked in its place: one asm file per stretch between them,
  `asm/code_<address>.s`, each ending with `.align 2, 0` (zero padding,
  not a Thumb nop). A function the disassembly calls inside a cut-out
  stretch has to be named as the source names it (gbadisasm.cfg).
- A literal-pool word whose value games/n2/symbols.txt names is written
  as that name (`.4byte gLevelTable`), and so is the `ldr`'s `@ =`
  comment; the linker gives it the same value.
- Only the code is kept (up to CODE_END): the rest of the ROM is
  games/n2/data/rom_data.s's incbin.
"""
import re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CODE_START, CODE_END = 0x08000000, 0x0805BEA8
BUILD = 'build/ntranced'

HEADER = """\
@ Crash Bandicoot 2: N-Tranced (Europe): the code, 0x%08X-0x%08X.
@ Generated by games/n2/disasm.py from games/n2/gbadisasm.cfg; regenerate
@ instead of editing while it is still the bootstrap (docs/n_tranced.md).

\t.include "asm/macros.inc"

\t.syntax unified

\t.text

"""

LDSCRIPT = """\
/* Generated by games/n2/disasm.py from games/n2/objects.txt: the N-Tranced
 * ROM in order, its disassembly and the shared sources linked in its
 * place, then the incbin'd rest (docs/n_tranced.md). */
OUTPUT_ARCH(arm)
SECTIONS
{
\t. = 0x08000000;
\tROM :
\tALIGN(4)
\t{
%s
\t\t%s/games/n2/data/rom_data.o(.rodata);
\t} = 0

\tINCLUDE "games/n2/symbols.txt"

\t/DISCARD/ :
\t{
\t\t*(.comment);
\t\t*(.ARM.attributes);
\t}
}
"""

SYMBOL = re.compile(r'^(\w+) = (0x[0-9A-Fa-f]+);')
WORD = re.compile(r'(\.4byte |@ =)0x([0-9A-F]{8})\b')
ADDS = re.compile(r'^\tadds (r([0-7])), \1, #(0x[0-9a-fA-F]+|\d+)$')
LABEL = re.compile(r'^(\w+): @ 0x([0-9A-Fa-f]{8})$')


def objects():
    out = []
    for line in (HERE / 'objects.txt').read_text().splitlines():
        line = line.split('#')[0].split()
        if line:
            out.append((int(line[0], 16), int(line[1], 16), line[2]))
    return out


def main():
    gbadisasm = sys.argv[1]
    rom = sys.argv[2] if len(sys.argv) > 2 else str(ROOT / 'baserom_n2.gba')
    out = subprocess.run([gbadisasm, rom, '-c', str(HERE / 'gbadisasm.cfg')],
                         capture_output=True, text=True, check=True).stdout.split('\n')
    names = {}
    for line in (HERE / 'symbols.txt').read_text().splitlines():
        m = SYMBOL.match(line)
        if m:
            names[int(m.group(2), 16)] = m.group(1)
    lines = []
    for line in out:
        line = WORD.sub(lambda m: m.group(1) + names[int(m.group(2), 16)]
                        if int(m.group(2), 16) in names else m.group(0), line)
        m = ADDS.match(line)
        if m:
            n, k = int(m.group(2)), int(m.group(3), 0)
            line = '\t.2byte 0x%04X @ adds %s, %s, #%d (GAS would pick the 0x3000 encoding)' % (
                0x1C00 | k << 6 | n << 3 | n, m.group(1), m.group(1), k)
        lines.append(line)

    # where each function starts: the line of its `*_func_start`
    starts = {}
    for i, line in enumerate(lines):
        m = LABEL.match(line)
        if m and i and '_func_start' in lines[i - 1]:
            starts[int(m.group(2), 16)] = i - 1
    starts[CODE_END] = len(lines)

    objs = objects()
    cuts = []  # (first line, end line) of each object's stretch
    for addr, size, src in objs:
        for a in (addr, addr + size):
            if a not in starts:
                sys.exit('%s: no function starts at 0x%08X in the disassembly' % (src, a))
        cuts.append((starts[addr], starts[addr + size]))

    asm = HERE / 'asm'
    for f in asm.glob('*.s'):
        f.unlink()
    script = []
    pos, at = 0, CODE_START
    pieces = [(cs, ce, o) for (cs, ce), o in zip(cuts, objs)] + [(len(lines), len(lines), None)]
    for cs, ce, o in pieces:
        if cs > pos:
            name = 'code_%08X' % at
            body = '\n'.join(lines[pos:cs]).strip('\n')
            (asm / (name + '.s')).write_text(HEADER % (at, o[0] if o else CODE_END) + body + '\n\t.align 2, 0\n')
            script.append('\t\t%s/games/n2/asm/%s.o(.text);' % (BUILD, name))
        if o:
            script.append('\t\t%s/%s.o(.text);' % (BUILD, o[2].rsplit('.', 1)[0]))
            at = o[0] + o[1]
        pos = ce
    (HERE / 'ldscript.txt').write_text(LDSCRIPT % ('\n'.join(script), BUILD))

    # labels cut out with an object but still used by the disassembly
    kept = '\n'.join(l for k, l in enumerate(lines) if not any(cs <= k < ce for cs, ce in cuts))
    for cs, ce in cuts:
        for k in range(cs, ce):
            m = LABEL.match(lines[k])
            if m and re.search(r'\b%s\b' % m.group(1), kept):
                print('note: %s (0x%s) is cut out but still used: the object must define it'
                      % (m.group(1), m.group(2)))


if __name__ == '__main__':
    main()
