"""Every data file's JSON Schema, and which files each describes (#1167, docs/editors.md).

The schemas are built from the domains' models (crashdata.levels.schema,
crashdata.cutscenes.schema, crashdata.graphics.schema,
crashdata.audio.schema) and written, with index.json (which files each
one describes, as globs from the tree's root), to
packages/crashdata/schemas/ for editors:

    tools/schemas.py write [DIR]    write them (DIR: packages/crashdata/schemas/)
    tools/schemas.py --check        fail if what is written differs from the model's
    tools/schemas.py validate [--game xs|n2] [--json]
                                    validate the game's files against them

`make schemas` writes them; CI runs `--check`, so a change to a model's
fields comes with its schemas.
"""
import fnmatch
import json
from pathlib import Path

from crashdata.common import diagnostics as D
from crashdata.common import schema as S
from crashdata.common.game import GAMES, ROOT

SCHEMAS_DIR = Path(ROOT) / "packages" / "crashdata" / "schemas"


def domains():
    """(the directory under games/<game>/ the globs are in, {name: (builder, globs)}) per domain."""
    from crashdata.audio import schema as audio
    from crashdata.cutscenes import schema as cutscenes
    from crashdata.graphics import schema as graphics
    from crashdata.levels import schema as levels
    return [("data/levels", levels.SCHEMAS), ("data", cutscenes.SCHEMAS), ("graphics", graphics.SCHEMAS),
            ("sound", audio.SCHEMAS)]


def build():
    """{schema file name: the schema}, in a stable order."""
    out = {}
    for _, schemas in domains():
        for name, (builder, _) in schemas.items():
            out["%s.schema.json" % name] = builder()
    return dict(sorted(out.items()))


def globs():
    """[(glob from the tree's root, schema file name)]: games/*/... for every game."""
    return [("games/*/%s/%s" % (sub, g), "%s.schema.json" % name)
            for sub, schemas in domains() for name, (_, file_globs) in schemas.items() for g in file_globs]


def index():
    """index.json: per schema, the files it describes (`fileMatch`, as an
    editor's JSON settings take them)."""
    by = {}
    for g, name in globs():
        by.setdefault(name, []).append(g)
    return {"$comment": "Generated by tools/schemas.py from crashdata (docs/editors.md): don't edit.",
            "schemas": [{"schema": name, "fileMatch": files} for name, files in sorted(by.items())]}


def dumps(v):
    return json.dumps(v, indent=2, ensure_ascii=False) + "\n"


def rendered():
    """{file name: text} of everything tools/schemas.py writes."""
    out = {name: dumps(s) for name, s in build().items()}
    out["index.json"] = dumps(index())
    return out


def write(out_dir=SCHEMAS_DIR):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    want = rendered()
    for name, text in want.items():
        p = out_dir / name
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
    for p in out_dir.glob("*.json"):
        if p.name not in want:
            p.unlink()
    return sorted(want)


def check(out_dir=SCHEMAS_DIR):
    """The differences between out_dir and the model's schemas, as Diagnostics."""
    out_dir = Path(out_dir)
    want = rendered()
    diags = []
    rel = out_dir.relative_to(ROOT) if out_dir.is_absolute() and out_dir.is_relative_to(ROOT) else out_dir
    for name, text in want.items():
        p = out_dir / name
        if not p.exists():
            diags.append(D.Diagnostic("missing: run `make schemas` (tools/schemas.py write)", rel / name,
                                      code="schema-stale"))
        elif p.read_text() != text:
            diags.append(D.Diagnostic("out of date with the model: run `make schemas` (tools/schemas.py write)",
                                      rel / name, code="schema-stale"))
    for p in sorted(out_dir.glob("*.json")):
        if p.name not in want:
            diags.append(D.Diagnostic("no schema of the model is called that: remove it (`make schemas`)",
                                      rel / p.name, code="schema-stale"))
    return diags


def files(game, root=None):
    """[(path, schema file name)] of the game's data files: each file the
    schemas describe, in a stable order."""
    root = Path(root if root is not None else game.root)
    out, seen = [], set()
    for g, name in globs():
        pattern = g.replace("games/*/", "games/%s/" % game.name, 1)
        for p in sorted(root.glob(pattern)):
            if p.is_file() and p not in seen:
                seen.add(p)
                out.append((p, name))
    return out


def schema_for(path):
    """The schema file name describing `path` (from the tree's root, or any
    path with a games/<game>/ part), or None."""
    p = Path(path).as_posix()
    if not p.startswith("games/"):
        i = p.rfind("/games/")
        if i < 0:
            return None
        p = p[i + 1:]
    for g, name in globs():
        if fnmatch.fnmatchcase(p, g) or fnmatch.fnmatchcase(p, g.replace("**/", "")):
            return name
    return None


_built = {}


def get(name):
    """A schema by file name (built from the model, not read from disk)."""
    if not _built:
        _built.update(build())
    return _built[name]


def validate_file(path, name=None, root=None):
    """The Diagnostics of one file against its schema."""
    path = Path(path)
    shown = path.relative_to(root) if root is not None and path.is_relative_to(root) else path
    try:
        data = D.read_json(path)
    except D.DataError as e:
        for d in e.diagnostics:
            d.file = shown.as_posix()
        return e.diagnostics
    diags = S.validate(get(name or schema_for(shown)), data, shown.as_posix())
    if diags:
        D.locate(diags, {shown.as_posix(): path.read_text(encoding="utf-8")})
    return diags


def validate_game(game, root=None):
    """The Diagnostics of every file of the game against its schema."""
    root = Path(root if root is not None else game.root)
    out = []
    for p, name in files(game, root):
        out += validate_file(p, name, root)
    return out


# The files load() has validated: (path, mtime, size), so a file read again
# unchanged isn't validated again.
_valid = set()


def load(path, name=None):
    """A data file, validated against its schema (named, or found by its
    path): a DataError (with line and column) if it breaks it. The loaders'
    way to read a file, so what the schema rejects the build rejects."""
    path = Path(path)
    data = D.read_json(path)
    name = name or schema_for(path)
    if name is None:
        return data
    st = path.stat()
    key = (str(path.resolve()), st.st_mtime_ns, st.st_size, name)
    if key in _valid:
        return data
    shown = path.as_posix()
    if path.is_absolute() and path.resolve().is_relative_to(Path(ROOT).resolve()):
        shown = path.resolve().relative_to(Path(ROOT).resolve()).as_posix()
    diags = S.validate(get(name), data, shown)
    if diags:
        D.locate(diags, {shown: path.read_text(encoding="utf-8")})
        raise D.DataError(diags)
    _valid.add(key)
    return data


__all__ = ["GAMES", "build", "check", "files", "get", "index", "load", "schema_for", "validate_file",
           "validate_game", "write"]
